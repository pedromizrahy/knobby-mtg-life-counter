static pk_gacha_entry_t lab_catalog[PK_LAB_DEX_COUNT];
static bool initialized=false;
const pk_gacha_entry_t *pk_lab_dex_catalog(size_t *count)
{
    if(!count)return NULL;
    if(!initialized){
        for(size_t i=0;i<PK_LAB_DEX_COUNT;i++){
            lab_catalog[i].species=species_data[i].species;
            lab_catalog[i].tier=species_data[i].tier;
            lab_catalog[i].sprite_ready=1U; /* simulated only; SD validated separately */
        }
        initialized=true;
    }
    *count=PK_LAB_DEX_COUNT;
    return lab_catalog;
}
const char *pk_lab_dex_name(uint16_t species)
{
    if(species==778U)return "MIMIKYU";
    if(species<1U || species>PK_LAB_DEX_COUNT)return NULL;
    return species_data[species-1U].name;
}
uint8_t pk_lab_dex_tier(uint16_t species)
{
    if(species<1U || species>PK_LAB_DEX_COUNT)return PK_TIER_COUNT;
    return species_data[species-1U].tier;
}
